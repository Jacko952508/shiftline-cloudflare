import assert from 'node:assert/strict';
import * as THREE from 'three';
import {readFileSync} from 'node:fs';
import {createFinishPortal,updateFinishPortal,disposeFinishPortal,FINISH_PORTAL_COLORS} from '../public/finish-portal-v174.js';
import {createTrack,poseObject} from '../public/race-track.js';
let count=0;const palettes=new Set();
for(let course=1;course<=6;course++){
 const track=createTrack(course),scene=new THREE.Scene(),portal=createFinishPortal(course);
 poseObject(portal,track.frame(track.length-3));scene.add(portal);
 assert.equal(portal.userData.finishPortal.version,174);
 assert.equal(portal.userData.finishPortal.course,course);
 assert.ok(portal.children.length>=7);
 assert.ok(portal.children.every(x=>x.geometry&&x.material));
 assert.ok(!portal.children.some(x=>x.name.includes('FINISH sign')));
 assert.ok(portal.userData.finishPortal.apertureRadius>6.3);
 assert.ok(portal.userData.finishPortal.ringRadius<=7.4);
 assert.ok(portal.position.distanceTo(track.frame(track.length-3).p)<.00001);
 updateFinishPortal(portal,5,950);
 assert.equal(portal.visible,false);
 updateFinishPortal(portal,10,315);
 assert.equal(portal.visible,true);
 assert.ok(portal.userData.finishPortal.spiral.material.uniforms.uApproach.value>0);
 const before=portal.userData.finishPortal.spiral.material.uniforms.uApproach.value;
 updateFinishPortal(portal,22,18,true);
 assert.ok(portal.userData.finishPortal.spiral.material.uniforms.uApproach.value>before);
 assert.ok(FINISH_PORTAL_COLORS[course].length===3);
 palettes.add(FINISH_PORTAL_COLORS[course].join(','));
 let disposed=0;portal.traverse(x=>{x.geometry?.addEventListener('dispose',()=>disposed++);});
 disposeFinishPortal(scene,portal);
 assert.equal(scene.children.includes(portal),false);
 assert.ok(disposed>=7);count++;
}
assert.equal(palettes.size,6);
const engine=readFileSync(new URL('../public/race-engine.js',import.meta.url),'utf8');
assert.ok(engine.includes('finishGate=createFinishPortal(course);'));
assert.ok(engine.includes('updateFinishPortal(finishGate,time,track.length-along,boost)'));
assert.ok(engine.includes('if(along>=track.length)finishRace()'),'Original race timing must not change');
assert.ok(!engine.includes("fillText('FINISH'"),'Old sign must be removed');
assert.ok(engine.includes('disposeFinishPortal(scene,finishGate)'));
console.log('PASS SHIFT LINE V174 six distinct glowing vortex destinations, approach animation, disposal and unchanged finish timing ('+count+' tracks)');
