import assert from 'node:assert/strict';
import * as THREE from '../public/vendor/three.module.js';
import{installFleetPrecision}from'../public/fleet-precision-v121.js';
import{installShipExhaust}from'../public/ship-exhaust-v119.js';
const seen=new Set(),types=new Set();
for(let index=0;index<6;index++){
 const root=new THREE.Group(),ship=new THREE.Group(),owned=[];
 ship.add(root);
 root.userData.finMounts=[{side:-1,baseY:.06,footX:.4,footZ:.5,kind:'structural'},{side:1,baseY:.06,footX:.4,footZ:.5,kind:index===5?'sword-blade':'structural'}];
 const mats={hull:new THREE.MeshPhysicalMaterial({color:0xbdd5ea}),polished:new THREE.MeshPhysicalMaterial({color:0xf0f0f0}),graphite:new THREE.MeshStandardMaterial(),carbon:new THREE.MeshStandardMaterial(),trim:new THREE.MeshStandardMaterial({color:0x55ccff}),glow:new THREE.MeshBasicMaterial(),premium:false};
 const custom={engine:index%5,trail:index%5};
 const result=installFleetPrecision(ship,root,index,custom,{materials:mats,owned,high:true});
 assert.equal(result.engineSockets,2,'two structurally seated engines');
 assert.equal(result.finFillets,2,'tail fillets follow actual mount records');
 assert.ok(result.structuralJoins>=2,'welded engine mounts');
 assert.ok(result.surfaceMarks>=2,'unique surface language');
 assert.ok(root.children.some(m=>m.name.includes('load-bearing-nozzle-collar')));
 assert.equal(ship.userData.fleetPrecision,result);
 assert.equal(root.children.filter(m=>m.name.includes('fin-root-cast-shoe')).length,2);
 seen.add(result.model);
 const fx=installShipExhaust(ship,root,index,custom,true);
 assert.equal(fx.actors.length,2);
 assert.equal(fx.actors[0].shockRings.length,2);
 assert.equal(fx.hasPlumes,true);
 fx.update(.33,true,false);
 assert.ok(fx.actors[0].shockRings.every(x=>x.visible),'boost shock diamonds visible');
 assert.ok(fx.length>1.15,'boost actually lengthens plasma');
 types.add(fx.engineProfile.name);
 for(const mat of owned)mat.dispose();
 for(const mat of Object.values(mats))mat.dispose();
 const geometries=new Set(),materials=new Set();
 root.traverse(m=>{if(m.geometry)geometries.add(m.geometry);if(m.material)materials.add(m.material);});
 geometries.forEach(g=>g.dispose());materials.forEach(m=>m.dispose());
}
assert.equal(seen.size,6,'six distinct craft names');
assert.equal(types.size,5,'five independent engine plume profiles');
const root=new THREE.Group(),ship=new THREE.Group();
const low=installShipExhaust(ship,root,0,{engine:0,trail:0},false);
assert.equal(low.actors[0].shockRings.length,0,'mobile rival gets no expensive glow-ring meshes');
low.update(.2,true,true);
console.log('V121 craft geometry, mounts, boost trails and rival-lite smoke tests passed');
