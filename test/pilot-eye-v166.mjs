import assert from 'node:assert/strict';
import * as THREE from 'three';
import {sealedLoft} from '../public/fleet-sculpture-v162.js';
import {setPilotView,placePilotCamera,inspectPilotSilhouette} from '../public/pilot-view-v166.js';
import {readFile} from 'node:fs/promises';

// Exact sculpted hull sampling, not a generic triangular stand-in.
const stations=[[-1.49,.012,.018,-.014],[-1.21,.0736,.055,0],[-.60,.1748,.105,.015]];
const full=sealedLoft(stations,32),nose=sealedLoft(stations,32,false);
assert.equal(nose.attributes.position.count,full.attributes.position.count-34);
assert.ok(nose.index.count<full.index.count);
const ship=new THREE.Group(),root=new THREE.Group();ship.add(root);
const original=new THREE.Mesh(full,new THREE.MeshBasicMaterial());root.add(original);
const glass=new THREE.Mesh(new THREE.BoxGeometry(.2,.2,.5),new THREE.MeshBasicMaterial({transparent:true,opacity:.4}));root.add(glass);
const tip=new THREE.Mesh(nose,original.material);tip.name='genuine-forward-loft';tip.visible=false;root.add(tip);
const seat=new THREE.Object3D();seat.position.set(0,.325,-.16);root.add(seat);
root.userData.pilotRig={version:166,seat,nose:tip,parts:[tip],eyeLocal:seat.position.toArray(),model:0,edition:0};
ship.position.set(3,4,-9);ship.scale.setScalar(.83);ship.rotateY(.4);
const p=new THREE.Vector3();
assert.ok(placePilotCamera(ship,p));const local=new THREE.Vector3(0,.325,-.16).applyMatrix4(root.matrixWorld);assert.ok(p.distanceTo(local)<1e-7);
const active=setPilotView(ship,true);
assert.equal(active.version,166);assert.equal(tip.visible,true);assert.equal(original.visible,false);assert.equal(glass.visible,false);assert.equal(ship.visible,true);
const camera=new THREE.PerspectiveCamera(78,390/844,.1,100);camera.position.copy(p);camera.quaternion.copy(ship.quaternion);camera.updateMatrixWorld();
const silhouette=inspectPilotSilhouette(ship,camera);
assert.ok(silhouette.visibleParts[0].forward>0);
assert.equal(silhouette.localEye[1],.325);
setPilotView(ship,false);assert.equal(tip.visible,false);assert.equal(original.visible,true);assert.equal(glass.visible,true);
assert.equal(ship.visible,true);
setPilotView(ship,true,false);assert.equal(ship.visible,false);setPilotView(ship,false,true);assert.equal(ship.visible,true);
const engine=await readFile(new URL('../public/race-engine.js',import.meta.url),'utf8');
assert.ok(engine.includes('placePilotCamera(player,pilotEye)'));
assert.ok(engine.includes('setPilotView(player,firstPerson'));
const fleet=await readFile(new URL('../public/fleet-sculpture-v162.js',import.meta.url),'utf8');
assert.ok(fleet.includes('if(options.pilotModel)'));
assert.ok(fleet.includes('seat.position.set(0,eyeY,eyeZ)'));
assert.ok(fleet.includes('pilot nacelle nose / original Gemini profile'));
assert.ok(fleet.includes('parts=[nose]'));
const seatVals=fleet.match(/eyeY=\[([^\]]+)\]\[index\],eyeZ=\[([^\]]+)\]\[index\]/);
assert.ok(seatVals,'Expected six calibrated pilot seats');
assert.equal(seatVals[1].split(',').length,6);assert.equal(seatVals[2].split(',').length,6);
console.log('PASS V166 real forward fuselage geometry, 6 pilot-seat anchors, world pose, cockpit visibility switching, active nose projection');
